"""Tests for queue discovery.

Regression coverage for:
- issue #61: an error queue whose name does not share the main queue's prefix
  is excluded from the ``list_queues`` prefix check and wrongly treated as
  missing.
- issue #43: ``botocore.errorfactory.QueueNameExists`` when the error queue
  already exists but does not share a prefix with the main queue (e.g. queue
  names auto-generated by CloudFormation).
"""

import boto3
import pytest
from moto import mock_aws

from sqs_launcher import SqsLauncher
from sqs_listener import SqsListener


class _Listener(SqsListener):
    def handle_message(self, body, attributes, messages_attributes):
        pass


@mock_aws
def test_existing_error_queue_without_shared_prefix_is_discovered():
    """Pre-existing error queue with a different prefix must be detected,
    not recreated (which would raise QueueNameExists when attrs differ)."""
    sqs = boto3.client("sqs", region_name="us-east-1")
    sqs.create_queue(QueueName="process-queue")
    # Distinct attributes so a re-create attempt raises QueueNameExists,
    # exactly reproducing issue #43.
    sqs.create_queue(
        QueueName="error-queue", Attributes={"VisibilityTimeout": "1234"}
    )

    # Must not raise.
    listener = _Listener(
        "process-queue", error_queue="error-queue", region_name="us-east-1"
    )

    assert listener._queue_url.endswith("/process-queue")
    assert listener._error_queue_url.endswith("/error-queue")


@mock_aws
def test_main_and_error_queue_created_when_missing():
    """When neither queue exists they should both be created."""
    listener = _Listener(
        "main-q", error_queue="totally-different-error-q", region_name="us-east-1"
    )

    sqs = boto3.client("sqs", region_name="us-east-1")
    urls = sqs.list_queues().get("QueueUrls", [])
    names = {u.split("/")[-1] for u in urls}
    assert "main-q" in names
    assert "totally-different-error-q" in names
    assert listener._error_queue_url.endswith("/totally-different-error-q")


@mock_aws
def test_listener_discovers_main_queue_that_is_prefix_of_another():
    """A queue whose name is a prefix of another must resolve to itself."""
    sqs = boto3.client("sqs", region_name="us-east-1")
    sqs.create_queue(QueueName="orders")
    sqs.create_queue(QueueName="orders-archive")

    listener = _Listener("orders", region_name="us-east-1")
    assert listener._queue_url.endswith("/orders")


@mock_aws
def test_launcher_resolves_exact_queue_when_prefix_of_another():
    sqs = boto3.client("sqs", region_name="us-east-1")
    sqs.create_queue(QueueName="orders")
    sqs.create_queue(QueueName="orders-archive")

    launcher = SqsLauncher("orders")
    assert launcher._queue_url.endswith("/orders")


@mock_aws
def test_launcher_raises_when_queue_missing_and_not_creating():
    with pytest.raises(ValueError):
        SqsLauncher("no-such-queue", create_queue=False)
